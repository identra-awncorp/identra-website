type SeoTranslation = {
  readonly siteName: string;
  readonly defaultTitle: string;
  readonly defaultDescription: string;
  readonly organizationDescription: string;
  readonly imageAlt: string;
  readonly blogTitleSuffix: string;
  readonly notFoundTitle: string;
  readonly notFoundDescription: string;
  readonly routeTitles: Record<AppView, string>;
  readonly routeDescriptions?: Partial<Record<AppView, string>>;
  readonly descriptionTemplates: Record<SeoRouteGroup, string>;
  readonly blogPosts: Partial<Record<BlogDetailId, BlogSeoCopy>>;
};

export const getSeoRouteDescription = (
  seo: SeoTranslation,
  view: AppView,
): string => {
  const routeTitle = seo.routeTitles[view];
  return seo.routeDescriptions?.[view]
    ?? seo.descriptionTemplates[SEO_ROUTE_GROUPS[view]].replace(/\{page\}/g, routeTitle);
};

